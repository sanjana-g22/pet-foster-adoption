-- Person B: adopter profiles, applications, adoptions, follow-ups and vectors.
CREATE TABLE adopter_profiles (
  user_id int PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  home_type home_type NOT NULL DEFAULT 'apartment',
  has_children boolean NOT NULL DEFAULT false,
  has_other_pets boolean NOT NULL DEFAULT false,
  experience experience_level NOT NULL DEFAULT 'first_time',
  activity_level smallint NOT NULL DEFAULT 3 CHECK (activity_level BETWEEN 1 AND 5),
  lifestyle_text text NOT NULL DEFAULT '',
  preferred_species species_type[],
  preferred_size size_type[],
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE applications (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id int NOT NULL REFERENCES pets(id) ON DELETE RESTRICT,
  adopter_user_id int NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  status application_status NOT NULL DEFAULT 'submitted',
  message text NOT NULL DEFAULT '',
  reviewer_user_id int REFERENCES users(id) ON DELETE SET NULL,
  review_note text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_applications_pet_adopter UNIQUE (pet_id, adopter_user_id),
  CONSTRAINT chk_application_message_length CHECK (length(message) <= 4000)
);
CREATE INDEX idx_applications_adopter_date ON applications(adopter_user_id, submitted_at DESC);
CREATE INDEX idx_applications_review_queue ON applications(status, submitted_at) WHERE status IN ('submitted','under_review');

CREATE TABLE adoptions (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id int NOT NULL REFERENCES pets(id) ON DELETE RESTRICT,
  application_id int NOT NULL UNIQUE REFERENCES applications(id) ON DELETE RESTRICT,
  adopter_user_id int NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  approved_by int REFERENCES users(id) ON DELETE SET NULL,
  adopted_at timestamptz NOT NULL DEFAULT now(),
  notes text
);
CREATE UNIQUE INDEX uq_one_adoption_per_pet ON adoptions(pet_id);

CREATE TABLE followups (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  adoption_id int NOT NULL REFERENCES adoptions(id) ON DELETE CASCADE,
  due_date date NOT NULL,
  day_number smallint NOT NULL CHECK (day_number IN (7,30,90)),
  status followup_status NOT NULL DEFAULT 'scheduled',
  adopter_notes text,
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_followup_day UNIQUE (adoption_id, day_number)
);
CREATE INDEX idx_followups_due ON followups(status, due_date);

CREATE TABLE pet_embeddings (
  pet_id int PRIMARY KEY REFERENCES pets(id) ON DELETE CASCADE,
  embedding vector(384) NOT NULL,
  source_text text NOT NULL,
  model_name text NOT NULL DEFAULT 'Xenova/all-MiniLM-L6-v2',
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE adopter_embeddings (
  user_id int PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  embedding vector(384) NOT NULL,
  source_text text NOT NULL,
  model_name text NOT NULL DEFAULT 'Xenova/all-MiniLM-L6-v2',
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- HNSW cosine index for semantic nearest-neighbour search.
CREATE INDEX idx_pet_embeddings_hnsw ON pet_embeddings USING hnsw (embedding vector_cosine_ops);

CREATE OR REPLACE VIEW v_adoption_funnel AS
SELECT
  count(*) FILTER (WHERE status = 'submitted') AS submitted,
  count(*) FILTER (WHERE status = 'under_review') AS under_review,
  count(*) FILTER (WHERE status = 'approved') AS approved,
  count(*) FILTER (WHERE status IN ('rejected','auto_rejected')) AS rejected,
  count(*) FILTER (WHERE status = 'withdrawn') AS withdrawn
FROM applications;

CREATE OR REPLACE VIEW v_average_stay_by_species AS
SELECT p.species,
       round(avg((COALESCE(a.adopted_at::date, CURRENT_DATE) - p.intake_date)::numeric), 1) AS average_days
FROM pets p
LEFT JOIN adoptions a ON a.pet_id = p.id
GROUP BY p.species;
