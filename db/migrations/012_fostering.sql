-- 012: foster profiles, placements, daily updates (Person A)

CREATE TABLE foster_profiles (
  id                 int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            int NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  max_capacity       smallint NOT NULL DEFAULT 1,
  species_preference species_type[] NOT NULL DEFAULT '{}',
  experience_level   experience_level NOT NULL DEFAULT 'some',
  has_yard           boolean NOT NULL DEFAULT false,
  address_city       text,
  notes              text,
  CONSTRAINT uq_foster_profiles_user UNIQUE (user_id),
  CONSTRAINT chk_fp_capacity_min CHECK (max_capacity >= 1)
);

CREATE TABLE foster_placements (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id            int NOT NULL REFERENCES pets(id),
  foster_user_id    int NOT NULL REFERENCES users(id),
  start_date        date NOT NULL DEFAULT CURRENT_DATE,
  expected_end_date date,
  end_date          date,
  status            placement_status NOT NULL DEFAULT 'active',
  end_reason        placement_end_reason,
  notes             text,
  created_by        int REFERENCES users(id) ON DELETE SET NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_placement_end_after_start
    CHECK (end_date IS NULL OR end_date >= start_date),
  CONSTRAINT chk_placement_expected_after_start
    CHECK (expected_end_date IS NULL OR expected_end_date >= start_date),
  CONSTRAINT chk_placement_active_has_no_end
    CHECK (status <> 'active' OR end_date IS NULL)
);

-- A pet can have only ONE active placement
CREATE UNIQUE INDEX uq_one_active_placement_per_pet
  ON foster_placements(pet_id) WHERE status = 'active';
CREATE INDEX idx_placements_foster_status
  ON foster_placements(foster_user_id, status);

CREATE TABLE foster_updates (
  id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placement_id   int NOT NULL REFERENCES foster_placements(id) ON DELETE CASCADE,
  update_date    date NOT NULL DEFAULT CURRENT_DATE,
  weight_kg      numeric(5,2),
  behaviour_note text,
  health_note    text,
  created_by     int REFERENCES users(id) ON DELETE SET NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_fu_weight_positive CHECK (weight_kg IS NULL OR weight_kg > 0)
);
