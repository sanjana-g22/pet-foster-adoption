-- 011: medical records, required vaccines, vaccinations (Person A)

CREATE TABLE medical_records (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      int NOT NULL REFERENCES pets(id) ON DELETE CASCADE,
  record_type medical_record_type NOT NULL,
  record_date date NOT NULL DEFAULT CURRENT_DATE,
  vet_name    text,
  diagnosis   text,
  treatment   text,
  notes       text,
  created_by  int REFERENCES users(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_medical_date_not_future CHECK (record_date <= CURRENT_DATE)
);

-- Reference list that drives the vaccination gate
CREATE TABLE required_vaccines (
  id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  species      species_type NOT NULL,
  vaccine_name text NOT NULL,
  CONSTRAINT uq_required_vaccine UNIQUE (species, vaccine_name)
);

INSERT INTO required_vaccines (species, vaccine_name) VALUES
