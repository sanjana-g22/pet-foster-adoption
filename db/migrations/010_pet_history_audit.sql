-- Reads the app user id set by the backend: SET LOCAL app.current_user_id = '<id>'
CREATE OR REPLACE FUNCTION fn_current_actor() RETURNS int AS $$
DECLARE v text;
BEGIN
  v := current_setting('app.current_user_id', true);
  IF v IS NULL OR v = '' THEN RETURN NULL; END IF;
  RETURN v::int;
END;
$$ LANGUAGE plpgsql STABLE;

-- Seed scripts set app.seed_mode = 'on' to bypass lifecycle rules while loading history
CREATE OR REPLACE FUNCTION fn_is_seed_mode() RETURNS boolean AS $$
BEGIN
  RETURN coalesce(current_setting('app.seed_mode', true), '') = 'on';
END;
$$ LANGUAGE plpgsql STABLE;

CREATE TABLE pet_status_history (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id     int NOT NULL REFERENCES pets(id) ON DELETE CASCADE,
  from_status pet_status,
  to_status  pet_status NOT NULL,
  changed_by int REFERENCES users(id) ON DELETE SET NULL,
  changed_at timestamptz NOT NULL DEFAULT now(),
  note       text
);
CREATE INDEX idx_psh_pet_time ON pet_status_history(pet_id, changed_at);

CREATE TABLE audit_log (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name    text NOT NULL,
  record_id     text,
  action        audit_action NOT NULL,
  old_data      jsonb,
  new_data      jsonb,
  actor_user_id int,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_table_record ON audit_log(table_name, record_id);
CREATE INDEX idx_audit_created ON audit_log(created_at DESC);
