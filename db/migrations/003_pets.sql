CREATE OR REPLACE FUNCTION fn_set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE pets (
  id                 int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name               text NOT NULL,
  species            species_type NOT NULL,
  breed              text,
  sex                sex_type NOT NULL DEFAULT 'unknown',
  age_months         int NOT NULL,
  size               size_type NOT NULL,
  weight_kg          numeric(5,2) NOT NULL,
  microchip_no       text,
  status             pet_status NOT NULL DEFAULT 'intake',
  intake_date        date NOT NULL DEFAULT CURRENT_DATE,
  intake_source      text,
  temperament        text,
  description        text,
  good_with_kids     boolean NOT NULL DEFAULT false,
  good_with_pets     boolean NOT NULL DEFAULT false,
  apartment_friendly boolean NOT NULL DEFAULT false,
  house_trained      boolean NOT NULL DEFAULT false,
  energy_level       smallint NOT NULL DEFAULT 3,
  special_needs      text,
  photo_url          text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_pets_microchip UNIQUE (microchip_no),
  CONSTRAINT chk_pets_name_not_blank CHECK (length(trim(name)) > 0),
  CONSTRAINT chk_pets_age_nonneg CHECK (age_months >= 0),
  CONSTRAINT chk_pets_weight_positive CHECK (weight_kg > 0),
  CONSTRAINT chk_pets_energy_range CHECK (energy_level BETWEEN 1 AND 5)
);

CREATE INDEX idx_pets_status ON pets(status);
CREATE INDEX idx_pets_species_size_status ON pets(species, size, status);

CREATE TRIGGER trg_pets_updated_at
  BEFORE UPDATE ON pets
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();